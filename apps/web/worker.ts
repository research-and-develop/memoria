/**
 * The Worker entry (wrangler `main`). Answers what needs no Next.js — the liveness probe and the client
 * galleries under `/g/` (plan p06 D6.1) — and hands every other request to OpenNext's generated worker.
 *
 * Why a custom entry: a path answered here costs ~1 ms CPU, a Next.js route several ms (and far more on
 * a cold start), against the free plan's 10 ms. Code reached from here must not import `server-only`
 * modules or `@repo/db/client` — it runs outside Next's bundle. The routing itself is
 * `routeEdge` (src/lib/edge/routes.ts, tested); this file only binds it to the env.
 *
 * OpenNext is imported LAZILY, on the Next path only: a gallery request on a fresh isolate never
 * evaluates Next's module (D6.5). So nothing here may import `.open-next/worker.js` statically — that
 * is why OpenNext's Durable Object classes are not re-exported (no `durable_objects` binding uses them;
 * enabling OpenNext caching that needs them re-adds them deliberately, at the cost of that laziness).
 * The module exists only after `opennextjs-cloudflare build` (wrangler bundles it): `@ts-ignore`, not
 * `@ts-expect-error`, because `tsc` sees this file (cloudflare-env.d.ts imports it) with and without a
 * build.
 */
import { d1Db } from '@repo/platform-cloudflare/d1';

import { edgeGalleryConfig } from './src/lib/edge/gallery/config';
import type { EdgeGalleryDeps, JsonCache } from './src/lib/edge/gallery/deps';
import { routeEdge } from './src/lib/edge/routes';

/** The gallery handler's deps from the env (plan p06 D6.5): built only for a request under `/g/`. */
async function galleryDeps(request: Request, env: CloudflareEnv, ctx: ExecutionContext): Promise<EdgeGalleryDeps> {
  return {
    db: d1Db(env.DB),
    // OpenNext's global types make ASSETS optional; without it every gallery page is the bare 503.
    assets: (path) => env.ASSETS?.fetch(new URL(path, request.url)) ?? Promise.resolve(new Response(null, { status: 404 })),
    // Inert on workers.dev and preview URLs (every view reads D1): a custom domain caches (D6.8).
    // `caches.default` is workerd's; the root tsconfig also loads the DOM's CacheStorage, which lacks it.
    cache: (caches as unknown as { default: JsonCache }).default,
    config: await edgeGalleryConfig(env),
    now: () => new Date(),
    waitUntil: (promise) => ctx.waitUntil(promise),
  };
}

export default {
  async fetch(request: Request, env: CloudflareEnv, ctx: ExecutionContext): Promise<Response> {
    return routeEdge(request, { env, gallery: () => galleryDeps(request, env, ctx) }, async () => {
      // @ts-ignore: generated by `opennextjs-cloudflare build`, resolved by wrangler
      const { default: openNext } = await import('./.open-next/worker.js');
      return openNext.fetch(request, env, ctx);
    });
  },
} satisfies ExportedHandler<CloudflareEnv>;
