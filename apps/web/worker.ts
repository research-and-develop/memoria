/**
 * The Worker entry (wrangler `main`). Answers what needs no Next.js — today the
 * liveness probe — and hands every other request to OpenNext's generated worker.
 *
 * Why a custom entry: a path answered here costs ~1 ms CPU, a Next.js route
 * several ms (and far more on a cold start), against the free plan's 10 ms.
 * Good candidates: files streamed from R2, a page cache in front of Next,
 * redirects (docs/recipes.md). Code reached from here must not import
 * `server-only` modules or `@repo/db/client` — it runs outside Next's bundle.
 *
 * It imports `.open-next/worker.js`, which exists only after `opennextjs-cloudflare
 * build` (wrangler bundles it): `@ts-ignore`, not `@ts-expect-error`, because
 * `tsc` sees this file (cloudflare-env.d.ts imports it) with and without a build.
 */
// @ts-ignore: generated by `opennextjs-cloudflare build`, resolved by wrangler
import openNext from './.open-next/worker.js';

import { edgeResponse } from './src/lib/edge/routes';

// OpenNext's Durable Object classes, re-exported for when its caching options use them.
// @ts-ignore: generated by `opennextjs-cloudflare build`, resolved by wrangler
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from './.open-next/worker.js';

export default {
  async fetch(request: Request, env: CloudflareEnv, ctx: ExecutionContext): Promise<Response> {
    const early = edgeResponse(request, env);
    if (early) return early;
    return openNext.fetch(request, env, ctx);
  },
} satisfies ExportedHandler<CloudflareEnv>;
